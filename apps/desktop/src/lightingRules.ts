import { hexToRgb } from "./color";
import type { KeyboardDefinition, LightingRule, Project, VisualKey } from "./domain";

/**
 * Turns project lighting data into a QMK C overlay:
 *
 * - every `perKey` colour becomes a static `rgb_matrix_set_color` call;
 * - every rule becomes a guarded call (`caps lock`, `layer_state_is`, or
 *   `matrix_is_on`) so the colour changes and reverts with the state.
 *
 * This is firmware source, not a VIA write. The app never flashes it; the
 * operator pastes it into the keymap, builds, and flashes through their own
 * QMK toolchain.
 */
export function generateLightingRulesC(
  project: Project,
  keyboard: KeyboardDefinition,
): string {
  const layout =
    keyboard.layouts.find((candidate) => candidate.id === project.target.layoutId) ??
    keyboard.layouts[0];
  const keys = layout?.keys ?? [];
  const byId = new Map(keys.map((key) => [key.id, key]));
  const profile = project.lightingProfiles?.[0];
  const perKey = Object.entries(profile?.perKey ?? {});
  const rules = (project.lightingRules ?? []).filter((rule) => rule.enabled !== false);

  const lines: string[] = [
    "// Generated by QMKUI. Paste at the end of your keymap.c, review, then build.",
    "// Per-key colours are applied first; state rules below override them.",
    '// Requires RGB_MATRIX_ENABLE.',
    '#include "quantum.h"',
    "",
    "#ifdef RGB_MATRIX_ENABLE",
    "static void qmkui_set_key_color(uint8_t row, uint8_t col, uint8_t r, uint8_t g, uint8_t b) {",
    "    uint8_t led = g_led_config.matrix_co[row][col];",
    "    if (led != NO_LED) {",
    "        rgb_matrix_set_color(led, r, g, b);",
    "    }",
    "}",
    "",
    "bool rgb_matrix_indicators_advanced_user(uint8_t led_min, uint8_t led_max) {",
    "    (void)led_min;",
    "    (void)led_max;",
    "",
    "    // Per-key colour overrides.",
  ];

  let staticCount = 0;
  for (const [keyId, color] of perKey) {
    const key = byId.get(keyId);
    const call = keyColorCall(key, color);
    if (!call) {
      continue;
    }
    lines.push(`    ${call}`);
    staticCount += 1;
  }
  if (staticCount === 0) {
    lines.push("    // (none)");
  }

  let ruleCount = 0;
  for (const rule of rules) {
    const block = ruleBlock(rule, byId);
    if (!block) {
      continue;
    }
    lines.push("");
    lines.push(...block);
    ruleCount += 1;
  }
  if (ruleCount === 0) {
    lines.push("");
    lines.push("    // State rules: none configured.");
  }

  lines.push("", "    return false;", "}", "#endif", "");
  return lines.join("\n");
}

export function lightingRulesCFileName(project: Project): string {
  const name = project.build.keymapName.replaceAll(/[^a-z0-9_-]+/gi, "-");
  return `${name || "qmkui"}-lighting-rules.c`;
}

function ruleBlock(
  rule: LightingRule,
  byId: Map<string, VisualKey>,
): string[] | null {
  const target = byId.get(rule.targetKeyId);
  const call = keyColorCall(target, rule.color, true);
  if (!call || !target) {
    return null;
  }
  const { trigger } = rule;
  if (trigger.kind === "lock") {
    const label = lockLabels[trigger.lock];
    return [
      `    // ${label} indicator: ${keyName(target)}`,
      `    if (host_keyboard_led_state().${lockMembers[trigger.lock]}) {`,
      `        ${call}`,
      "    }",
    ];
  }
  if (trigger.kind === "layer") {
    return [
      `    // Layer ${trigger.layerIndex} active: ${keyName(target)}`,
      `    if (layer_state_is(${trigger.layerIndex})) {`,
      `        ${call}`,
      "    }",
    ];
  }
  const source = byId.get(trigger.keyId);
  if (!source?.matrix) {
    return null;
  }
  return [
    `    // While ${keyName(source)} is held: ${keyName(target)}`,
    `    if (matrix_is_on(${source.matrix.row}, ${source.matrix.col})) {`,
    `        ${call}`,
    "    }",
  ];
}

function keyColorCall(
  key: VisualKey | undefined,
  color: string,
  withComment = false,
): string | null {
  if (!key?.matrix) {
    return null;
  }
  const { r, g, b } = hexToRgb(color);
  const comment = withComment ? ` // ${keyName(key)}` : "";
  return `qmkui_set_key_color(${key.matrix.row}, ${key.matrix.col}, ${r}, ${g}, ${b});${comment}`;
}

function keyName(key: VisualKey): string {
  const label = key.label ?? key.id;
  return label.replaceAll("*/", "").replaceAll("\n", " ");
}

const lockLabels: Record<"capsLock" | "numLock" | "scrollLock", string> = {
  capsLock: "Caps Lock",
  numLock: "Num Lock",
  scrollLock: "Scroll Lock",
};

// QMK's `host_keyboard_led_state()` uses snake_case members.
const lockMembers: Record<"capsLock" | "numLock" | "scrollLock", string> = {
  capsLock: "caps_lock",
  numLock: "num_lock",
  scrollLock: "scroll_lock",
};
