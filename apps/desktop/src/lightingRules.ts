import { hexToRgb } from "./color";
import type {
  KeyboardDefinition,
  LightingProfile,
  LightingRule,
  Project,
  VisualKey,
} from "./domain";

export type LightingLock = "capsLock" | "numLock" | "scrollLock";

/**
 * Turns project lighting data into a QMK C overlay:
 *
 * - every `perKey` colour becomes a static indicator colour;
 * - every rule becomes a guarded colour (`caps lock`, active layer, or held
 *   key) so the key changes and reverts with the state.
 *
 * This is firmware source, not a VIA write. The app never flashes it; the
 * operator pastes it into the keymap, builds, and flashes through their own
 * QMK toolchain.
 *
 * Returns a comment-only stub when the project's layout does not match the
 * keyboard, so we never emit row/column indexes for the wrong matrix.
 */
export function generateLightingRulesC(
  project: Project,
  keyboard: KeyboardDefinition,
  profile: LightingProfile | undefined = project.lightingProfiles?.[0],
): string {
  const layout = keyboard.layouts.find(
    (candidate) => candidate.id === project.target.layoutId,
  );
  if (!layout) {
    return "// QMKUI: no matching layout; no lighting overlay was exported.\n";
  }
  const keys = layout.keys;
  const byId = new Map(keys.map((key) => [key.id, key]));
  // Keyboard metadata may omit the matrix while every key still carries a
  // matrix position; derive the bounds from the keys in that case.
  const bounds = keyboard.matrix ?? derivedBounds(keys);
  const perKey = Object.entries(profile?.perKey ?? {});
  const rules = (project.lightingRules ?? []).filter((rule) => rule.enabled !== false);

  const lines: string[] = [
    "// Generated by QMKUI. Included by keymap.c; review, then build.",
    "// Per-key colours are applied first; state rules below override them.",
    "// Requires RGB_MATRIX_ENABLE.",
    '#include "quantum.h"',
    "",
    "#ifdef RGB_MATRIX_ENABLE",
    "static void qmkui_set_key_color(uint8_t row, uint8_t col,",
    "                                 uint8_t r, uint8_t g, uint8_t b) {",
    "    uint8_t led = g_led_config.matrix_co[row][col];",
    "    if (led != NO_LED) {",
    "        RGB_MATRIX_INDICATOR_SET_COLOR(led, r, g, b);",
    "    }",
    "}",
    "",
    "bool rgb_matrix_indicators_advanced_user(uint8_t led_min, uint8_t led_max) {",
    "    // Per-key colour overrides.",
  ];

  let staticCount = 0;
  for (const [keyId, color] of perKey) {
    const call = keyColorCall(byId.get(keyId), color, bounds);
    if (!call) {
      continue;
    }
    lines.push(`    ${call}`);
    staticCount += 1;
  }
  if (staticCount === 0) {
    lines.push("    // (none)");
  }

  let ruleCount = 0;
  for (const rule of rules) {
    const block = ruleBlock(rule, byId, bounds);
    if (!block) {
      continue;
    }
    lines.push("");
    lines.push(...block);
    ruleCount += 1;
  }
  if (ruleCount === 0) {
    lines.push("");
    lines.push("    // State rules: none configured.");
  }

  lines.push("", "    return false;", "}", "#endif", "");
  return lines.join("\n");
}

export function lockLabel(lock: LightingLock): string {
  return lockLabels[lock];
}

type MatrixBounds = KeyboardDefinition["matrix"];

function ruleBlock(
  rule: LightingRule,
  byId: Map<string, VisualKey>,
  bounds: MatrixBounds,
): string[] | null {
  const target = byId.get(rule.targetKeyId);
  const call = keyColorCall(target, rule.color, bounds, true);
  if (!call || !target) {
    return null;
  }
  const { trigger } = rule;
  if (trigger.kind === "lock") {
    return [
      `    // ${lockLabels[trigger.lock]} indicator: ${keyName(target)}`,
      `    if (host_keyboard_led_state().${lockMembers[trigger.lock]}) {`,
      `        ${call}`,
      "    }",
    ];
  }
  if (trigger.kind === "layer") {
    // Layer 0 is the default layer: it lives in `default_layer_state`, so
    // `layer_state_is(0)` is never true.
    const condition =
      trigger.layerIndex === 0
        ? "get_highest_layer(layer_state | default_layer_state) == 0"
        : `layer_state_is(${trigger.layerIndex})`;
    return [
      `    // Layer ${trigger.layerIndex} active: ${keyName(target)}`,
      `    if (${condition}) {`,
      `        ${call}`,
      "    }",
    ];
  }
  const source = byId.get(trigger.keyId);
  if (!source?.matrix || !inBounds(source, bounds)) {
    return null;
  }
  return [
    `    // While ${keyName(source)} is held: ${keyName(target)}`,
    `    if (matrix_is_on(${source.matrix.row}, ${source.matrix.col})) {`,
    `        ${call}`,
    "    }",
  ];
}

function keyColorCall(
  key: VisualKey | undefined,
  color: string,
  bounds: MatrixBounds,
  withComment = false,
): string | null {
  if (!key?.matrix || !inBounds(key, bounds)) {
    return null;
  }
  const { r, g, b } = hexToRgb(color);
  const comment = withComment ? ` // ${keyName(key)}` : "";
  return `qmkui_set_key_color(${key.matrix.row}, ${key.matrix.col}, ${r}, ${g}, ${b});${comment}`;
}

function derivedBounds(keys: VisualKey[]): MatrixBounds {
  let rows = 0;
  let cols = 0;
  let found = false;
  for (const key of keys) {
    if (!key.matrix) {
      continue;
    }
    found = true;
    rows = Math.max(rows, key.matrix.row + 1);
    cols = Math.max(cols, key.matrix.col + 1);
  }
  return found ? { rows, cols } : undefined;
}

function inBounds(key: VisualKey, bounds: MatrixBounds): boolean {
  if (!bounds || !key.matrix) {
    return false;
  }
  return key.matrix.row < bounds.rows && key.matrix.col < bounds.cols;
}

function keyName(key: VisualKey): string {
  return cCommentText(key.label ?? key.id);
}

/**
 * Text safe inside a `//` C comment. Drops comment terminators, line
 * continuations, and line breaks so generated source cannot be escaped.
 */
export function cCommentText(value: string): string {
  return value
    .replaceAll("\\", "")
    .replaceAll("\r", " ")
    .replaceAll("\n", " ")
    .replaceAll("*/", "");
}

const lockLabels: Record<LightingLock, string> = {
  capsLock: "Caps Lock",
  numLock: "Num Lock",
  scrollLock: "Scroll Lock",
};

// QMK's `host_keyboard_led_state()` uses snake_case members.
const lockMembers: Record<LightingLock, string> = {
  capsLock: "caps_lock",
  numLock: "num_lock",
  scrollLock: "scroll_lock",
};
