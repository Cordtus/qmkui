import { describe, expect, it } from "vitest";
import type { KeyboardDefinition, Project } from "./domain";
import { buildFirmwareBundle, firmwareBundleFileName } from "./firmwareBundle";

const keyboard: KeyboardDefinition = {
  id: "test-keyboard",
  displayName: "Test Keyboard",
  qmkKeyboard: "test/keyboard",
  matrix: { rows: 2, cols: 2 },
  layouts: [
    {
      id: "LAYOUT_test",
      qmkLayoutMacro: "LAYOUT_test",
      displayName: "Test",
      keys: [
        { id: "a", label: "A", x: 0, y: 0, matrix: { row: 0, col: 0 } },
        { id: "b", label: "B", x: 1, y: 0, matrix: { row: 0, col: 1 } },
      ],
    },
  ],
};

function project(): Project {
  return {
    schemaVersion: "0.1.0",
    id: "project",
    name: "Bundle Test",
    target: {
      keyboardId: keyboard.id,
      qmkKeyboard: keyboard.qmkKeyboard,
      layoutId: "LAYOUT_test",
      qmkLayoutMacro: "LAYOUT_test",
    },
    layers: [
      {
        id: "l0",
        index: 0,
        name: "Base",
        enabled: true,
        assignments: [
          { id: "a0", visualKeyId: "a", kind: "key", qmk: "KC_A" },
          { id: "b0", visualKeyId: "b", kind: "key", qmk: "MO(1)" },
        ],
      },
      {
        id: "l1",
        index: 1,
        name: "Fn",
        enabled: true,
        assignments: [
          { id: "a1", visualKeyId: "a", kind: "key", qmk: "KC_TRNS" },
          { id: "b1", visualKeyId: "b", kind: "key", qmk: "KC_MPLY" },
        ],
      },
    ],
    build: { mode: "localCli", keymapName: "bundle_map", outputPreference: "json" },
    lightingProfiles: [
      { id: "p", name: "Default", mode: "static", perKey: { a: "#ff0000" } },
    ],
    lightingRules: [
      {
        id: "rule",
        targetKeyId: "b",
        color: "#00ff00",
        trigger: { kind: "lock", lock: "capsLock" },
      },
    ],
  };
}

describe("firmware bundle", () => {
  it("builds a keymap, lighting overlay and instructions", () => {
    const files = buildFirmwareBundle(project(), keyboard)!;
    const byName = new Map(files.map((file) => [file.name, file.contents]));

    expect([...byName.keys()]).toEqual([
      "keymap.c",
      "qmkui-lighting-rules.c",
      "README.md",
    ]);
    const keymap = byName.get("keymap.c")!;
    expect(keymap).toContain("#include QMK_KEYBOARD_H");
    expect(keymap).toContain("const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS]");
    expect(keymap).toContain("[0] = LAYOUT_test(");
    expect(keymap).toContain("KC_A, MO(1),");
    expect(keymap).toContain("[1] = LAYOUT_test(");
    expect(keymap).toContain("KC_TRNS, KC_MPLY,");
    expect(keymap).toContain('#include "qmkui-lighting-rules.c"');

    const lighting = byName.get("qmkui-lighting-rules.c")!;
    expect(lighting).toContain("RGB_MATRIX_INDICATOR_SET_COLOR");
    expect(lighting).toContain("host_keyboard_led_state().caps_lock");

    const readme = byName.get("README.md")!;
    expect(readme).toContain(
      "qmk compile -kb test/keyboard -km bundle_map",
    );
    expect(readme).toContain("QMKUI did not build or flash this bundle.");
  });

  it("derives matrix bounds from the keys when keyboard metadata omits them", () => {
    const noMatrix = { ...keyboard, matrix: undefined };
    const files = buildFirmwareBundle(project(), noMatrix)!;
    const lighting = files.find((file) => file.name === "qmkui-lighting-rules.c")!;
    expect(lighting.contents).toContain("RGB_MATRIX_INDICATOR_SET_COLOR");
  });

  it("falls back to a no-op overlay when no key has a matrix position", () => {
    const noMatrix = {
      ...keyboard,
      matrix: undefined,
      layouts: [
        {
          ...keyboard.layouts[0]!,
          keys: keyboard.layouts[0]!.keys.map(({ matrix: _matrix, ...key }) => key),
        },
      ],
    };
    const files = buildFirmwareBundle(project(), noMatrix)!;
    const lighting = files.find((file) => file.name === "qmkui-lighting-rules.c")!;
    expect(lighting.contents).toContain("State rules: none configured");
    expect(lighting.contents).not.toContain("\n    qmkui_set_key_color(");
  });

  it("sanitizes the project name and empty keycodes", () => {
    const unsafe = project();
    unsafe.name = "bad */ name\\";
    unsafe.layers[0]!.assignments[0]!.qmk = "";

    const files = buildFirmwareBundle(unsafe, keyboard)!;
    const keymap = files.find((file) => file.name === "keymap.c")!.contents;
    const readme = files.find((file) => file.name === "README.md")!.contents;

    expect(keymap).toContain('// Generated by QMKUI from "bad  name"');
    expect(keymap).not.toContain("*/");
    expect(keymap).toContain("KC_NO, MO(1),");
    expect(readme).toContain("# bad  name — QMK firmware bundle");
    expect(readme).not.toContain("bad */ name\\");
  });

  it("never emits an unsafe keycode expression", () => {
    const unsafe = project();
    unsafe.layers[0]!.assignments[0]!.qmk = "KC_A\n#include <evil.h>";

    const files = buildFirmwareBundle(unsafe, keyboard)!;
    const keymap = files.find((file) => file.name === "keymap.c")!.contents;

    expect(keymap).toContain("KC_NO, MO(1),");
    expect(keymap).not.toContain("evil");
  });

  it("returns null when the layout does not match", () => {
    const mismatched = project();
    mismatched.target.layoutId = "LAYOUT_other";
    expect(buildFirmwareBundle(mismatched, keyboard)).toBeNull();
  });

  it("names the zip after the keymap", () => {
    expect(firmwareBundleFileName(project())).toBe("bundle_map-firmware.zip");
  });
});
