import type { KeyboardDefinition, LightingProfile, Project } from "./domain";
import { isSafeQmkKeycode } from "./keycodes";
import { cCommentText, generateLightingRulesC } from "./lightingRules";

export type FirmwareBundleFile = {
  name: string;
  contents: string;
};

/**
 * Builds a drop-in QMK keymap directory: the project keymap as C, the lighting
 * indicator overlay, and build/flash instructions. This is firmware source —
 * QMKUI never builds or flashes it; the operator runs QMK CLI, Toolbox, or the
 * gated `qmkui-flash` adapter.
 *
 * Returns `null` when the project's layout does not match the keyboard.
 */
export function buildFirmwareBundle(
  project: Project,
  keyboard: KeyboardDefinition,
  profile: LightingProfile | undefined = project.lightingProfiles?.[0],
): FirmwareBundleFile[] | null {
  const layout = keyboard.layouts.find(
    (candidate) => candidate.id === project.target.layoutId,
  );
  if (!layout) {
    return null;
  }

  // `layout.keys` order is the LAYOUT macro order for info.json-derived
  // definitions (the catalog's contract); the QMK JSON export relies on it too.

  const layers = [...project.layers].sort((left, right) => left.index - right.index);
  const keymap: string[] = [
    `// Generated by QMKUI from "${cCommentText(project.name)}". Review before building.`,
    "#include QMK_KEYBOARD_H",
    "",
    "const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {",
  ];
  layers.forEach((layer) => {
    const keycodes = layout.keys.map((key) => {
      const qmk = layer.assignments
        .find((assignment) => assignment.visualKeyId === key.id)
        ?.qmk.trim();
      // Validation rejects unsafe expressions; this keeps a malformed imported
      // project from ever reaching C if validation is bypassed.
      return qmk && isSafeQmkKeycode(qmk) ? qmk : "KC_NO";
    });
    keymap.push(`    [${layer.index}] = ${layout.qmkLayoutMacro}(`);
    keymap.push(...wrapC(keycodes, 8).map((line) => `        ${line}`));
    keymap.push("    ),");
  });
  keymap.push("};", "", '#include "qmkui-lighting-rules.c"', "");

  const lighting = generateLightingRulesC(project, keyboard, profile);

  return [
    { name: "keymap.c", contents: keymap.join("\n") },
    { name: "qmkui-lighting-rules.c", contents: lighting },
    { name: "README.md", contents: readme(project, keyboard) },
  ];
}

export function firmwareBundleFileName(project: Project): string {
  const name = project.build.keymapName.replaceAll(/[^a-z0-9_-]+/gi, "-");
  return `${name || "qmkui"}-firmware.zip`;
}

function wrapC(items: string[], perLine: number): string[] {
  const lines: string[] = [];
  for (let index = 0; index < items.length; index += perLine) {
    lines.push(`${items.slice(index, index + perLine).join(", ")},`);
  }
  return lines;
}

function readme(project: Project, keyboard: KeyboardDefinition): string {
  const keymap = project.build.keymapName;
  const title = cCommentText(project.name);
  return `# ${title} — QMK firmware bundle

Generated by QMKUI from the current project. It contains:

- \`keymap.c\` — the project layers.
- \`qmkui-lighting-rules.c\` — per-key colours and state rules (included by
  \`keymap.c\`).
- this README.

## Build and flash

Copy these files into your QMK checkout:

\`\`\`sh
dest=qmk_firmware/keyboards/${project.target.qmkKeyboard}/keymaps/${keymap}
mkdir -p "$dest"
cp keymap.c qmkui-lighting-rules.c "$dest/"
\`\`\`

Compile and flash with the QMK CLI:

\`\`\`sh
qmk compile -kb ${project.target.qmkKeyboard} -km ${keymap}
qmk flash  -kb ${project.target.qmkKeyboard} -km ${keymap}
\`\`\`

Or compile with \`qmk compile\` and flash the resulting \`.bin\`/\`.hex\` with
QMK Toolbox.

## Notes

- Review the generated C before flashing; it was generated, not compiled.
- QMKUI did not build or flash this bundle.
- The target is **${keyboard.displayName}** (\`${project.target.qmkKeyboard}\`).
- Lighting rules need \`RGB_MATRIX_ENABLE\`; the rules file is a no-op otherwise.
`;
}
